/// Gets the assistant's reply (Gemini when `GEMINI_API_KEY` is set, otherwise
/// a placeholder), then saves the user's message and the reply; returns both.
/// Nothing is saved if the AI call fails, so the student can just resend.
#[tauri::command]
pub async fn send_chat_message(
    db: State<'_, Db>,
    content: String,
    attachment: Option<String>,
) -> AppResult<Vec<ChatMessage>> {
    super::require_premium(&db).await?; // Premium only
    let content = required_text(&content, "Message")?;
    let attachment = optional_text(attachment);
    let uid = db.user_id().await?;

    let reply = match crate::ai::GeminiConfig::from_env() {
        None => placeholder_reply(&content, attachment.as_deref()),
        Some(config) => {
            let limit = crate::ai::daily_limit();
            let sent_today: i64 = sqlx::query_scalar(
                "SELECT COUNT(*) FROM chat_messages WHERE user_id = $1 AND role = 'user' AND created_at::date = CURRENT_DATE",
            )
            .bind(uid)
            .fetch_one(&db.pool)
            .await?;
            if sent_today >= limit {
                return Err(AppError::new(format!(
                    "You've reached today's limit of {limit} AI messages. It resets tomorrow."
                )));
            }
            // Recent conversation (oldest first) + the new message.
            let mut recent: Vec<(String, String)> = sqlx::query_as(
                "SELECT role, content FROM chat_messages WHERE user_id = $1 ORDER BY id DESC LIMIT $2",
            )
            .bind(uid)
            .bind(crate::ai::HISTORY_MESSAGES)
            .fetch_all(&db.pool)
            .await?;
            recent.reverse();
            let mut turns: Vec<crate::ai::Turn> =
                recent.iter().map(|(role, text)| crate::ai::Turn { role, content: text }).collect();
            let with_attachment = match &attachment {
                Some(name) => format!("{content}

(Attached file: {name}. Only its name is shared, not its contents.)"),
                None => content.clone(),
            };
            turns.push(crate::ai::Turn { role: "user", content: &with_attachment });
            crate::ai::reply(&config, &turns).await?
        }
    };

    let mut tx = db.pool.begin().await?;
    let first: bool = sqlx::query_scalar("SELECT NOT EXISTS (SELECT 1 FROM chat_messages WHERE user_id = $1)")
        .bind(uid)
        .fetch_one(&mut *tx)
        .await?;
    let user_msg_id: i64 = sqlx::query_scalar(
        "INSERT INTO chat_messages (user_id, role, content, attachment) VALUES ($1, 'user', $2, $3) RETURNING id",
    )
    .bind(uid)
    .bind(&content)
    .bind(&attachment)
    .fetch_one(&mut *tx)
    .await?;
    sqlx::query("INSERT INTO chat_messages (user_id, role, content) VALUES ($1, 'assistant', $2)")
        .bind(uid)
        .bind(&reply)
        .execute(&mut *tx)
        .await?;
    if first {
        let subtitle: String = content.chars().take(60).collect();
        log_activity(&mut tx, uid, "AI Assistant Chat", &subtitle, "chat", "/ai-study/chat").await?;
    }
    let messages = sqlx::query_as::<_, ChatMessage>(&format!(
        "{CHAT_SELECT} WHERE m.user_id = $1 AND m.id >= $2 ORDER BY m.id"
    ))
    .bind(uid)
    .bind(user_msg_id)
    .fetch_all(&mut *tx)
    .await?;
    tx.commit().await?;
    Ok(messages)
}

/// Deletes the whole conversation and its "AI Assistant Chat" entries in
/// recent study activity.
#[tauri::command]
pub async fn clear_chat(db: State<'_, Db>) -> AppResult<()> {
    let uid = super::require_premium(&db).await?; // Premium only
    let mut tx = db.pool.begin().await?;
    sqlx::query("DELETE FROM chat_messages WHERE user_id = $1")
        .bind(uid)
        .execute(&mut *tx)
        .await?;
    sqlx::query("DELETE FROM study_activity WHERE user_id = $1 AND kind = 'chat'")
        .bind(uid)
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;
    Ok(())
}
