/// A question to insert, from the bank or from the AI.
pub(crate) struct NewQuestion {
    pub kind: String,
    pub prompt: String,
    pub case_text: Option<String>,
    pub image: Option<String>,
    pub choices: Vec<String>,
    pub answer: usize,
    pub explanation: Option<String>,
    pub hint: Option<String>,
}

fn bank_questions(kinds: &[String], topic: &str, count: usize, seed: u64) -> Vec<NewQuestion> {
    question_bank::pick(kinds, topic, count, &mut Rng::new(seed))
        .into_iter()
        .map(|q| NewQuestion {
            kind: q.kind.to_string(),
            prompt: q.prompt.to_string(),
            case_text: q.case_text.map(str::to_string),
            image: q.image.map(str::to_string),
            choices: q.choices.iter().map(|c| c.to_string()).collect(),
            answer: q.answer,
            explanation: Some(q.explanation.to_string()),
            hint: Some(q.hint.to_string()),
        })
        .collect()
}

/// AI questions, with the choices shuffled so the answer position varies.
fn ai_questions(generated: Vec<crate::ai::GeneratedQuestion>, seed: u64) -> Vec<NewQuestion> {
    let mut rng = Rng::new(seed);
    generated
        .into_iter()
        .map(|q| {
            let (choices, answer) = if q.kind == "true_false" {
                (q.choices, q.answer)
            } else {
                let mut order: Vec<usize> = (0..q.choices.len()).collect();
                rng.shuffle(&mut order);
                let answer = order.iter().position(|&i| i == q.answer).unwrap_or(0);
                (order.iter().map(|&i| q.choices[i].clone()).collect(), answer)
            };
            NewQuestion {
                kind: q.kind,
                prompt: q.prompt,
                case_text: q.case_text,
                image: None,
                choices,
                answer,
                explanation: Some(q.explanation).filter(|e| !e.is_empty()),
                hint: q.hint,
            }
        })
        .collect()
}

