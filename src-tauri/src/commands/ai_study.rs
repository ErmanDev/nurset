/// Feedback shown after finishing a quiz.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct QuizFeedback {
    /// "ai" (written by NurSet AI) or "basic" (built from the answers, no AI).
    pub source: String,
    pub summary: String,
    pub strengths: Vec<String>,
    pub review_topics: Vec<crate::ai::ReviewTopic>,
    pub next_steps: Vec<String>,
    /// Why AI feedback wasn't used, when it wasn't.
    pub notice: Option<String>,
}

#[derive(Serialize, Deserialize)]
struct StoredFeedback {
    source: String,
    #[serde(flatten)]
    body: crate::ai::QuizFeedbackBody,
}

/// Feedback without AI: the score and the questions that were missed.
fn basic_feedback(rows: &[QuestionRow]) -> crate::ai::QuizFeedbackBody {
    let total = rows.len();
    let correct = rows.iter().filter(|r| r.is_correct == Some(true)).count();
    let pct = if total == 0 { 0 } else { correct * 100 / total };
    let summary = match pct {
        90..=100 => format!("Excellent! You got {correct} of {total} right ({pct}%)."),
        75..=89 => format!("Good work: {correct} of {total} right ({pct}%). Review the few you missed below."),
        50..=74 => format!("You got {correct} of {total} right ({pct}%). Go over the missed questions below, then retake the quiz."),
        _ => format!("You got {correct} of {total} right ({pct}%). Review the topics below and try the quiz again."),
    };
    let review_topics = rows
        .iter()
        .filter(|r| r.is_correct != Some(true))
        .take(4)
        .map(|r| crate::ai::ReviewTopic {
            topic: r.prompt.chars().take(90).collect::<String>(),
            why: match (r.choices.0.get(r.answer_index as usize), &r.explanation) {
                (Some(answer), Some(e)) => format!("Correct answer: {answer}. {e}"),
                (Some(answer), None) => format!("Correct answer: {answer}."),
                _ => String::from("Review this question's explanation."),
            },
        })
        .collect();
    crate::ai::QuizFeedbackBody {
        summary,
        strengths: vec![],
        review_topics,
        next_steps: vec![
            "Read the explanation for each question you missed.".into(),
            "Retake the quiz to check what you've learned.".into(),
        ],
    }
}

/// Feedback for a finished quiz: NurSet AI when available (and within the
/// daily limit), otherwise basic feedback. Cached until the quiz is retaken.
#[tauri::command]
pub async fn get_quiz_feedback(db: State<'_, Db>, id: i64) -> AppResult<QuizFeedback> {
    let uid = super::require_premium(&db).await?; // Premium only
    let quiz: Option<(String, bool, Option<Json<StoredFeedback>>)> = sqlx::query_as(
        "SELECT title, completed_at IS NOT NULL, feedback FROM quizzes WHERE id = $1 AND user_id = $2",
    )
    .bind(id)
    .bind(uid)
    .fetch_optional(&db.pool)
    .await?;
    let (title, completed, cached) = quiz.ok_or_else(|| not_found("Quiz", id))?;
    if !completed {
        return Err(AppError::new("Finish the quiz to get feedback"));
    }
    if let Some(Json(stored)) = cached {
        return Ok(QuizFeedback {
            source: stored.source,
            summary: stored.body.summary,
            strengths: stored.body.strengths,
            review_topics: stored.body.review_topics,
            next_steps: stored.body.next_steps,
            notice: None,
        });
    }

    let rows = sqlx::query_as::<_, QuestionRow>(&format!("{QUESTION_SELECT} WHERE q.id = $1 ORDER BY qq.position"))
        .bind(id)
        .fetch_all(&db.pool)
        .await?;

    let mut notice = None;
    let mut ai_body = None;
    if let Some(config) = crate::ai::GeminiConfig::from_env() {
        let limit = crate::ai::daily_feedback_limit();
        let used: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM quizzes WHERE user_id = $1 AND feedback->>'source' = 'ai' AND feedback_at::date = CURRENT_DATE",
        )
        .bind(uid)
        .fetch_one(&db.pool)
        .await?;
        if used >= limit {
            notice = Some(format!(
                "You've used today's {limit} AI quiz reviews, so this is basic feedback. AI reviews reset tomorrow."
            ));
        } else {
            let items: Vec<crate::ai::ReviewItem> = rows
                .iter()
                .take(50)
                .map(|r| crate::ai::ReviewItem {
                    kind: &r.kind,
                    prompt: &r.prompt,
                    case_text: r.case_text.as_deref(),
                    chosen: r.chosen_index.and_then(|c| r.choices.0.get(c as usize)).map(String::as_str),
                    correct_answer: r.choices.0.get(r.answer_index as usize).map(String::as_str).unwrap_or(""),
                    is_correct: r.is_correct == Some(true),
                })
                .collect();
            match crate::ai::quiz_feedback(&config, &title, &items).await {
                Ok(body) => ai_body = Some(body),
                Err(e) => notice = Some(format!("{e} Here's basic feedback instead.")),
            }
        }
    }
    let (source, body) = match ai_body {
        Some(body) => ("ai", body),
        None => ("basic", basic_feedback(&rows)),
    };

    // Cache AI feedback for this attempt. Basic feedback isn't cached, so a
    // later visit can still get an AI review once one is available.
    if source == "ai" {
        let stored = StoredFeedback { source: source.into(), body: body.clone() };
        sqlx::query("UPDATE quizzes SET feedback = $3, feedback_at = now() WHERE id = $1 AND user_id = $2")
            .bind(id)
            .bind(uid)
            .bind(Json(&stored))
            .execute(&db.pool)
            .await?;
    }
    Ok(QuizFeedback {
        source: source.into(),
        summary: body.summary,
        strengths: body.strengths,
        review_topics: body.review_topics,
        next_steps: body.next_steps,
        notice,
    })
}

/// Clears all answers so the quiz can be taken again.
#[tauri::command]
pub async fn restart_quiz(db: State<'_, Db>, id: i64) -> AppResult<QuizDetail> {
    let uid = super::require_premium(&db).await?; // Premium only
    let changed = sqlx::query(
        "UPDATE quizzes SET completed_at = NULL, score = NULL, feedback = NULL, feedback_at = NULL
         WHERE id = $1 AND user_id = $2",
    )
        .bind(id)
        .bind(uid)
        .execute(&db.pool)
        .await?
        .rows_affected();
    if changed == 0 {
        return Err(not_found("Quiz", id));
    }
    sqlx::query(
        "UPDATE quiz_questions SET chosen_index = NULL, is_correct = NULL, answered_at = NULL WHERE quiz_id = $1",
    )
    .bind(id)
    .execute(&db.pool)
    .await?;
    quiz_detail(&db.pool, uid, id).await
}

