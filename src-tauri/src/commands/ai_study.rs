#[tauri::command]
pub async fn create_quiz(db: State<'_, Db>, input: NewQuiz) -> AppResult<CreatedQuiz> {
    super::require_premium(&db).await?; // Premium only
    let topic = required_text(&input.topic, "Quiz topic")?;
    let kinds: Vec<String> = input
        .question_types
        .into_iter()
        .filter(|k| QUESTION_KINDS.contains(&k.as_str()))
        .collect();
    if kinds.is_empty() {
        return Err(AppError::new("Choose at least one question type"));
    }
    if !(1..=100).contains(&input.count) {
        return Err(AppError::new("Number of questions must be between 1 and 100"));
    }
    let uid = db.user_id().await?;
    let notes = optional_text(input.notes);
    let count = input.count as usize;
    let seed = seed_from_clock();

    // AI generation (Gemini) when configured and within today's limit;
    // otherwise, or if the AI fails, NurSet's built-in question bank.
    let mut source = "bank";
    let mut notice: Option<String> = None;
    let mut questions: Vec<NewQuestion> = Vec::new();
    if let Some(config) = crate::ai::GeminiConfig::from_env() {
        let limit = crate::ai::daily_quiz_limit();
        let used_today: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM quizzes WHERE user_id = $1 AND source = 'ai' AND created_at::date = CURRENT_DATE",
        )
        .bind(uid)
        .fetch_one(&db.pool)
        .await?;
        if used_today >= limit {
            notice = Some(format!(
                "You've used today's {limit} AI quizzes, so this quiz uses NurSet's built-in practice questions. \
                 AI quizzes reset tomorrow."
            ));
        } else {
            let max = crate::ai::max_quiz_questions();
            let ai_count = count.min(max);
            match crate::ai::generate_quiz(&config, &topic, notes.as_deref(), &kinds, ai_count).await {
                Ok(generated) => {
                    questions = ai_questions(generated, seed);
                    source = "ai";
                    if count > max {
                        notice = Some(format!("AI quizzes have up to {max} questions each, so this one has {}.", questions.len()));
                    }
                }
                // A non-nursing topic is the student's to fix, not a reason to fall back.
                Err(e) if e.to_string() == crate::ai::QUIZ_OFF_TOPIC => return Err(e),
                Err(e) => {
                    notice = Some(format!("{e} This quiz uses NurSet's built-in practice questions instead."));
                }
            }
        }
    }
    if questions.is_empty() {
        questions = bank_questions(&kinds, &topic, count, seed);
    }

    let mut tx = db.pool.begin().await?;
    let id = insert_quiz(&mut tx, uid, &topic, notes.as_deref(), &kinds, &questions, source).await?;
    let question_count: i64 = sqlx::query_scalar("SELECT COUNT(*) FROM quiz_questions WHERE quiz_id = $1")
        .bind(id)
        .fetch_one(&mut *tx)
        .await?;
    let types = kinds.iter().map(|k| kind_label(k)).collect::<Vec<_>>().join(", ");
    log_activity(
        &mut tx,
        uid,
        &format!("{topic} Quiz"),
        &format!("{question_count} questions · {types}"),
        "quiz",
        &format!("/ai-study/quiz/{id}"),
    )
    .await?;
    tx.commit().await?;

    Ok(CreatedQuiz {
        quiz: quiz_summary(&db.pool, uid, id).await?,
        requested: input.count,
        source: source.to_string(),
        notice,
    })
}

